import { ApiProperty, ApiPropertyOptional } from '@nestjs/swagger';
import {
  EvidenceItemStatus,
  ValidationStatus,
} from '../interfaces/validation.interfaces';

export class EvidenceValidationDetailDto {
  @ApiProperty({
    description: 'Target field name in candidate extraction',
    example: 'courses[0].course_code',
  })
  field!: string;

  @ApiProperty({
    description: 'Extracted field value evaluated for grounding in context evidence',
    example: 'CS101',
  })
  value!: unknown;

  @ApiProperty({
    description: 'Grounding status against source document text',
    enum: [
      'SUPPORTED',
      'UNSUPPORTED_BY_EVIDENCE',
      'MISSING_SUPPORTED_FIELD',
      'SOURCE_REFERENCE_INVALID',
    ],
    example: 'SUPPORTED',
  })
  status!: EvidenceItemStatus;

  @ApiPropertyOptional({
    description: 'Context source snippet or coordinate reference matching this value',
    example: { source: 'tables[0].rows[0][0]' },
  })
  evidenceRef?: unknown;

  @ApiPropertyOptional({
    description: 'Diagnostic justification if field failed grounding check',
    example: 'Value not found in document tables or text sections.',
  })
  reason?: string;
}

export class EvidenceValidationSummaryDto {
  @ApiProperty({
    description: 'Number of candidate fields positively grounded in source document evidence',
    example: 18,
  })
  supported_values!: number;

  @ApiProperty({
    description: 'Number of candidate fields unsupported by evidence (hallucination suspects)',
    example: 0,
  })
  unsupported_values!: number;

  @ApiProperty({
    description: 'Number of expected fields missing from candidate extraction',
    example: 0,
  })
  missing_supported_values!: number;

  @ApiProperty({
    description: 'Number of invalid or non-existent source references cited by model',
    example: 0,
  })
  invalid_source_references!: number;

  @ApiProperty({
    description: 'Detailed list of validated fields with evidence grounding status',
    type: () => [EvidenceValidationDetailDto],
  })
  details!: EvidenceValidationDetailDto[];
}

export class QualityMetricsDto {
  @ApiProperty({
    description: 'Ratio of true positive extracted fields over total extracted fields (0.0 to 1.0)',
    example: 1.0,
  })
  field_precision!: number;

  @ApiProperty({
    description: 'Ratio of true positive extracted fields over ground truth fields in source (0.0 to 1.0)',
    example: 1.0,
  })
  field_recall!: number;

  @ApiProperty({
    description: 'Precision calculated across complete structured record entities (e.g. course rows)',
    example: 1.0,
  })
  record_precision!: number;

  @ApiProperty({
    description: 'Recall calculated across complete structured record entities',
    example: 1.0,
  })
  record_recall!: number;

  @ApiProperty({
    description: 'Total number of structured data rows present in source context tables',
    example: 12,
  })
  source_rows_count!: number;

  @ApiProperty({
    description: 'Total number of structured data records produced by LLM candidate extraction',
    example: 12,
  })
  candidate_records_count!: number;

  @ApiPropertyOptional({
    description: 'Total pipeline latency in milliseconds',
    example: 842,
  })
  latency_ms?: number;

  @ApiPropertyOptional({
    description: 'Prompt token count processed by LLM provider',
    example: 1250,
  })
  input_tokens?: number;

  @ApiPropertyOptional({
    description: 'Completion token count generated by LLM provider',
    example: 410,
  })
  output_tokens?: number;
}

export class SchemaErrorDto {
  @ApiProperty({
    description: 'JSON path to invalid property',
    example: 'courses[2].credits',
  })
  path!: string;

  @ApiProperty({
    description: 'Schema constraint violation explanation',
    example: 'Expected number, received string',
  })
  message!: string;
}

export class ValidationReportDto {
  @ApiProperty({
    description: 'Schema version for validation report artifact',
    example: 'edmo-validation-report-0.1',
  })
  schema_version!: 'edmo-validation-report-0.1';

  @ApiProperty({
    description: 'Overall validation pipeline outcome status',
    enum: ['PASS', 'WARN', 'FAIL'],
    example: 'PASS',
  })
  status!: ValidationStatus;

  @ApiProperty({
    description: 'True if candidate JSON adheres 100% to the target document schema specification',
    example: true,
  })
  schema_valid!: boolean;

  @ApiProperty({
    description: 'Array of schema constraint violations, if any',
    type: () => [SchemaErrorDto],
    example: [],
  })
  schema_errors!: SchemaErrorDto[];

  @ApiProperty({
    description: 'Evidence grounding breakdown and hallucination verification results',
    type: () => EvidenceValidationSummaryDto,
  })
  evidence_validation!: EvidenceValidationSummaryDto;

  @ApiProperty({
    description: 'Total count of detected hallucinations or unsupported claims',
    example: 0,
  })
  hallucination_flags!: number;

  @ApiProperty({
    description: 'Non-fatal quality warnings or normalization notices',
    type: [String],
    example: [],
  })
  warnings!: string[];

  @ApiProperty({
    description: 'Statistical quality metrics, precision, recall, and token telemetry',
    type: () => QualityMetricsDto,
  })
  quality_metrics!: QualityMetricsDto;
}
